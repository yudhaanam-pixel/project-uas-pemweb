-- =========================================================
-- 1. KODE PEMBERSIHAN (Mereset database dari nol)
-- =========================================================
DROP TABLE IF EXISTS public.rekam_medis CASCADE;
DROP TABLE IF EXISTS public.kunjungan CASCADE;
DROP TABLE IF EXISTS public.jadwal_praktik CASCADE;
DROP TABLE IF EXISTS public.pasien CASCADE;
DROP TABLE IF EXISTS public.dokter CASCADE;
DROP TABLE IF EXISTS public.layanan CASCADE;
DROP TABLE IF EXISTS public.pengguna CASCADE;

-- Aktifkan fungsi pembuat UUID otomatis
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- =========================================================
-- 2. PEMBUATAN STRUKTUR TABEL BARU
-- =========================================================

-- Tabel 1: Pengguna
CREATE TABLE public.pengguna (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    nama TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    peran TEXT NOT NULL CHECK (peran IN ('admin', 'dokter', 'pasien')),
    aktif BOOLEAN DEFAULT true,
    dibuat_pada TIMESTAMPTZ DEFAULT NOW()
);

-- Tabel 2: Layanan
CREATE TABLE public.layanan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama TEXT NOT NULL,
    deskripsi TEXT,
    aktif BOOLEAN DEFAULT true,
    dibuat_pada TIMESTAMPTZ DEFAULT NOW()
);

-- Tabel 3: Dokter
CREATE TABLE public.dokter (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pengguna_id UUID REFERENCES public.pengguna(id) ON DELETE CASCADE,
    nama TEXT NOT NULL,
    spesialis TEXT,
    no_str TEXT,
    aktif BOOLEAN DEFAULT true,
    dibuat_pada TIMESTAMPTZ DEFAULT NOW()
);

-- Tabel 4: Pasien
CREATE TABLE public.pasien (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pengguna_id UUID REFERENCES public.pengguna(id) ON DELETE CASCADE,
    nama TEXT NOT NULL,
    jenis_kelamin TEXT,
    no_hp TEXT,
    alamat TEXT,
    dibuat_pada TIMESTAMPTZ DEFAULT NOW()
);

-- Tabel 5: Jadwal Praktik
CREATE TABLE public.jadwal_praktik (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dokter_id BIGINT REFERENCES public.dokter(id) ON DELETE CASCADE,
    hari SMALLINT NOT NULL,
    jam_mulai TIME NOT NULL,
    jam_selesai TIME NOT NULL,
    kuota INTEGER DEFAULT 10,
    aktif BOOLEAN DEFAULT true
);

-- Tabel 6: Kunjungan (Sudah diperbaiki ke GENERATED BY DEFAULT)
CREATE TABLE public.kunjungan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pasien_id BIGINT REFERENCES public.pasien(id) ON DELETE CASCADE,
    dokter_id BIGINT REFERENCES public.dokter(id) ON DELETE CASCADE,
    layanan_id BIGINT REFERENCES public.layanan(id) ON DELETE CASCADE,
    jadwal_id BIGINT REFERENCES public.jadwal_praktik(id) ON DELETE CASCADE,
    tanggal DATE NOT NULL DEFAULT CURRENT_DATE,
    nomor_antrean INTEGER NOT NULL,
    keluhan TEXT,
    status TEXT NOT NULL DEFAULT 'aktif' CHECK (status IN ('aktif', 'selesai', 'batal')),
    dibuat_pada TIMESTAMPTZ DEFAULT NOW()
);

-- Tabel 7: Rekam Medis
CREATE TABLE public.rekam_medis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kunjungan_id BIGINT REFERENCES public.kunjungan(id) ON DELETE CASCADE,
    keluhan TEXT,
    diagnosis TEXT,
    tindakan TEXT,
    catatan TEXT,
    dibuat_pada TIMESTAMPTZ DEFAULT NOW()
);

